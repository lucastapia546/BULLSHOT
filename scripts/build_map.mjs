// Dev-only. Needs:  npm i us-atlas@3 topojson-client@3 d3-geo@3   then   node scripts/build_map.mjs
// Map data: US Census boundaries via us-atlas (ISC). Projection matches us-atlas's *-albers files.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature, mesh } from "topojson-client";
import { geoAlbersUsa, geoContains, geoPath } from "d3-geo";

const require = createRequire(import.meta.url);
const atlas = (f) => JSON.parse(readFileSync(require.resolve(`us-atlas/${f}`), "utf8"));
const proj = geoAlbersUsa().scale(1300).translate([487.5, 305]);
const W = 975, H = 610, STEP = 11;

const us = atlas("states-10m.json");
const nation = feature(us, us.objects.nation);
const path = geoPath(proj).digits(1);
const r = (n) => Math.round(n * 10) / 10;

// Dot grid: hex-offset rows, keep points that fall on land.
const dots = [];
for (let y = STEP / 2, row = 0; y < H; y += STEP * 0.866, row++) {
  for (let x = (row % 2 ? STEP : STEP / 2); x < W; x += STEP) {
    const ll = proj.invert([x, y]);
    if (ll && geoContains(nation, ll)) dots.push([r(x), r(y)]);
  }
}

